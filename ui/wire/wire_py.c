/* Writes wire.c's schema as a Python module, for the Anki bridge add-on's reader and writer
 * (anki/addon/amgi_bridge/bridge_wire.py). The add-on cannot load wire.wasm inside Anki, so it gets
 * the table itself instead: every kind's number, and its fields in wire order with their names and
 * types. ui/build.sh runs this into anki/addon/amgi_bridge/wire_schema.py, and tests/ui/wire_py.test.mjs
 * holds the committed file to this output, so the Python never holds a layout of its own. */
#include <stdio.h>
#include "wire.h"

uint8_t *wire_grow(uint8_t *p, uint32_t len, uint32_t cap) { (void)p, (void)len, (void)cap; return 0; }

static const char *const TYPE_NAMES[WT_TYPES] = {
  [WT_BOOL] = "BOOL", [WT_TRI] = "TRI", [WT_U32] = "U32", [WT_OPT] = "OPT", [WT_I32] = "I32", [WT_I64] = "I64",
  [WT_STR] = "STR", [WT_MODE] = "MODE", [WT_STRS] = "STRS", [WT_LIST] = "LIST", [WT_BYTES] = "BYTES",
};

static void fields(const wire_schema *s, int indent) {
  printf("(\n");
  for (uint32_t i = 0; i < s->n; i++) {
    const wire_field *f = &s->f[i];
    printf("%*s(\"%s\", %s, ", indent + 4, "", f->key, TYPE_NAMES[f->type]);
    if (f->type == WT_LIST) fields(f->sub, indent + 4);
    else printf("None");
    printf("),\n");
  }
  printf("%*s)", indent, "");
}

int main(void) {
  printf("# Generated by ui/wire/wire_py.c from ui/wire/wire.c's schema at every ui/build.sh: do not edit.\n"
         "# Change wire.c and build. tests/ui/wire_py.test.mjs holds this file to the build's output.\n"
         "# bridge_wire.py reads and writes messages with it.\n\n");
  printf("MAGIC = 0x%08X\n", WIRE_MAGIC);
  printf("MIME = \"%s\"\n", WIRE_MIME);
  printf("BRIDGE_PROTOCOL = %u\n", WIRE_BRIDGE_PROTOCOL);
  printf("NONE = 0x%08X\n", WIRE_NONE);
  printf("ABSENT = %d\n", (int)WIRE_ABSENT);
  printf("UNKNOWN = %u\n\n", WIRE_UNKNOWN);
  for (int t = 0; t < WT_TYPES; t++) printf("%s = %d\n", TYPE_NAMES[t], t);
  printf("\n# A mode's byte is its index; the last, \"\", is any name the table does not know.\nMODES = (");
  for (uint32_t m = 0; m < WIRE_MODES; m++) printf("%s\"%s\"", m ? ", " : "", wire_mode_name(m));
  printf(")\n\n# Each kind by name: its byte, and its fields in wire order as (name, type, item fields or None).\nKINDS = {\n");
  for (uint32_t k = 0; k < WK_KINDS; k++) {
    printf("    \"%s\": (%u, ", wire_kind_name(k), k);
    fields(wire_schema_of(k), 4);
    printf("),\n");
  }
  printf("}\n");
  return 0;
}
