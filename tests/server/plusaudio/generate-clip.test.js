'use strict';

// The Node side of the boundary generate-clip.js documents at its own top: text and a
// language in, one clip written to --out, a clean exit code, and nothing else load
// bearing on stdout or stderr. tests/anki/addon/test_generator.py proves the
// Python side of the same contract.
//
// `run()` is exercised here with a stubbed generator, never a real client - there
// is no API key in this environment and live calls are not authorised. `main()`'s own
// argument handling and its "no key" failure are exercised too, since both return before
// ever building a client or touching the network.

const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { sandboxEnv } = require('../../repo/sandbox-home.cjs');
const { test } = require('node:test');

const { main, parseArgs, run } = require('../../../plusaudio/generate-clip');
const { withEnvHidden } = require('./helpers/hide-env');
const { DAILY_CAP_EXIT, RATE_LIMITED_EXIT, parseRetryAfter } = require('../../../plusaudio/lib/cliExit');

function tempOutputPath() {
  return path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'plusaudio-generate-clip-')), 'clip.wav');
}

test('parseArgs collects the three flags and rejects an unknown one', () => {
  const options = parseArgs(['--text', '안녕', '--language', 'ko', '--out', '/tmp/x.mp3']);
  assert.deepEqual(options, { text: '안녕', language: 'ko', out: '/tmp/x.mp3' });

  assert.throws(() => parseArgs(['--bogus', 'x']), /unknown option --bogus/);
  assert.throws(() => parseArgs(['--text']), /--text needs a value/);
});

test('parseArgs collects the optional --reading flag', () => {
  const options = parseArgs(['--text', '行った', '--language', 'ja', '--out', '/tmp/x.mp3', '--reading', 'いった']);
  assert.deepEqual(options, { text: '行った', language: 'ja', out: '/tmp/x.mp3', reading: 'いった' });
});

test('run() writes the generated bytes to --out and returns exit code 0', async () => {
  const out = tempOutputPath();
  const clip = Buffer.from([1, 2, 3, 4]);
  const calls = [];
  const generate = async (request) => {
    calls.push(request);
    return clip;
  };

  const code = await run({ text: 'hello', language: 'ko', out }, generate);

  assert.equal(code, 0);
  assert.deepEqual(calls, [{ text: 'hello', language: 'ko', reading: '' }]);
  assert.deepEqual(fs.readFileSync(out), clip);
});

test('run() passes --reading through to the generator when given one', async () => {
  const out = tempOutputPath();
  const clip = Buffer.from([1, 2, 3, 4]);
  const calls = [];
  const generate = async (request) => {
    calls.push(request);
    return clip;
  };

  const code = await run({ text: '行った', language: 'ja', reading: 'いった', out }, generate);

  assert.equal(code, 0);
  assert.deepEqual(calls, [{ text: '行った', language: 'ja', reading: 'いった' }]);
});

test('run() writes nothing and returns exit code 1 when generation fails', async () => {
  const out = tempOutputPath();
  const generate = async () => {
    throw new Error('Failed to generate valid audio for "hello" after 3 attempts');
  };

  const code = await run({ text: 'hello', language: 'ko', out }, generate);

  assert.equal(code, 1);
  assert.equal(fs.existsSync(out), false);
});

/** run() with stdout and stderr captured. */
async function runCaptured(options, generate) {
  const out = [];
  const err = [];
  const realOut = process.stdout.write;
  const realErr = process.stderr.write;
  process.stdout.write = (chunk) => { out.push(String(chunk)); return true; };
  process.stderr.write = (chunk) => { err.push(String(chunk)); return true; };
  try {
    return { code: await run(options, generate), stdout: out.join(''), stderr: err.join('') };
  } finally {
    process.stdout.write = realOut;
    process.stderr.write = realErr;
  }
}

test('run() exits 3 on a rate limit and says on stdout how long the gate says to wait', async () => {
  const out = tempOutputPath();
  const limited = Object.assign(new Error('Gemini is limiting how many requests gemini-3.8-flash-tts takes per minute and asked to wait 52s.'), { rateLimited: true, retryAfterMs: 51234.6 });

  const { code, stdout, stderr } = await runCaptured({ text: 'hello', language: 'ko', out }, async () => { throw limited; });

  assert.equal(code, RATE_LIMITED_EXIT);
  assert.equal(code, 3);
  assert.equal(stdout, 'retry-after-ms=51235\n');
  assert.equal(parseRetryAfter(stdout), 51235);
  assert.equal(stderr.trim(), limited.message);
  assert.equal(fs.existsSync(out), false);
});

test('run() exits 4 on a spent daily cap, with nothing on stdout', async () => {
  const out = tempOutputPath();
  const daily = Object.assign(new Error("Your Gemini project's daily limit of 100 requests for gemini-3.8-flash-tts is used up."), { fatal: true, dailyCap: true });

  const { code, stdout } = await runCaptured({ text: 'hello', language: 'ko', out }, async () => { throw daily; });

  assert.equal(code, DAILY_CAP_EXIT);
  assert.equal(code, 4);
  assert.equal(stdout, '');
});

test('run() removes a stale clip left at --out by an earlier successful run', async () => {
  const out = tempOutputPath();
  fs.writeFileSync(out, Buffer.from('stale'));
  const generate = async () => {
    throw new Error('boom');
  };

  const code = await run({ text: 'hello', language: 'ko', out }, generate);

  assert.equal(code, 1);
  assert.equal(fs.existsSync(out), false);
});

test('main() returns exit code 2 and touches nothing when a required flag is missing', async () => {
  const out = tempOutputPath();
  const code = await main(['--text', 'hello', '--out', out]); // no --language
  assert.equal(code, 2);
  assert.equal(fs.existsSync(out), false);
});

/**
 * Runs main() with exactly `env` set for the key (undefined = unset), and
 * plusaudio/.env hidden: main() falls back to that real, gitignored file when a
 * variable is unset - the whole point of the fallback for a plain checkout - so
 * "unset" is only unset with it out of the way. See helpers/hide-env.js for why
 * that has to be lock-guarded rather than a plain rename.
 */
async function mainWithKeys(env, argv) {
  const names = ['GEMINI_API_KEY'];
  const previous = Object.fromEntries(names.map((name) => [name, process.env[name]]));
  const writes = [];
  const realWrite = process.stderr.write;
  for (const name of names) {
    if (env[name] === undefined) delete process.env[name];
    else process.env[name] = env[name];
  }
  try {
    return await withEnvHidden(async () => {
      process.stderr.write = (chunk) => {
        writes.push(String(chunk));
        return true;
      };
      try {
        return { code: await main(argv), stderr: writes.join('') };
      } finally {
        process.stderr.write = realWrite;
      }
    });
  } finally {
    for (const name of names) {
      if (previous[name] === undefined) delete process.env[name];
      else process.env[name] = previous[name];
    }
  }
}

test('main() returns exit code 1 with an actionable message when GEMINI_API_KEY is unset', async () => {
  const out = tempOutputPath();
  // An old OpenAI key is no help any more: Gemini is the only provider.
  process.env.OPENAI_API_KEY = 'sk-old';
  const { code, stderr } = await mainWithKeys({}, ['--text', 'hello', '--language', 'ko', '--out', out]);
  delete process.env.OPENAI_API_KEY;
  assert.equal(code, 1);
  assert.equal(fs.existsSync(out), false);
  assert.match(stderr, /GEMINI_API_KEY is not set/);
  assert.match(stderr, /https:\/\/aistudio\.google\.com\/apikey/);
  assert.equal(stderr.trim().split('\n').length, 1, 'one line: the app shows the last line verbatim');
});

test('main() prints usage and exits 0 on --help without requiring an API key', async () => {
  const previous = process.env.GEMINI_API_KEY;
  delete process.env.GEMINI_API_KEY;
  try {
    const code = await main(['--help']);
    assert.equal(code, 0);
  } finally {
    if (previous !== undefined) process.env.GEMINI_API_KEY = previous;
  }
});

// The one line of stderr a caller shows a person is the last one, and a run that fails
// has only its failure message to put there. Anything Node prints on its own - once a
// module-type warning for cardGeneration/*.ts, printed on every single run, which is what
// a failed clip was once recorded as having failed with - is noise ahead of it. So a run
// that loads the whole generator and does nothing wrong has to leave stderr empty.
test('loading the generator leaves stderr empty', () => {
  const result = spawnSync(process.execPath, [path.join(__dirname, '..', '..', '..', 'plusaudio', 'generate-clip.js'), '--help'], {
    env: sandboxEnv(),
    encoding: 'utf8',
  });
  assert.equal(result.status, 0);
  assert.equal(result.stderr, '');
});
