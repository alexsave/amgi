// tools/reindent4.py leaves a file alone as generated only when a comment in its first five lines carries a real
// generated-file marker. The word "generated" in prose does not exempt a file from the 4-space rule.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { sandboxEnv } from './sandbox-home.cjs';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const SCRIPT = path.join(ROOT, 'tools', 'reindent4.py');
const TWO = 'function f() {\n  if (1) {\n    return 2;\n  }\n}\n';

/** The files `--verify` names as offenders when run in a scratch git repo holding `files` (name -> text). */
function offenders(files) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'reindent4-'));
    try {
        execFileSync('git', ['init', '-q'], { cwd: dir });
        for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), text);
        execFileSync('git', ['add', '.'], { cwd: dir });
        const run = spawnSync('python3', ['-I', SCRIPT, '--verify'], { cwd: dir, encoding: 'utf8', env: sandboxEnv() });
        return [...run.stdout.matchAll(/^(\S+?):\d+: /gm)].map((m) => m[1]).sort();
    } finally {
        fs.rmSync(dir, { recursive: true, force: true });
    }
}

test('prose that says "generated" does not exempt a file, a real marker does', () => {
    const got = offenders({
        'prose.js': `// The host half of the file the build generated from the sources.\n// More prose, and do not edit this casually.\n${TWO}`,
        'plain.js': TWO,
        'marked.js': `// Generated by tools/make.sh: do not edit.\n${TWO}`,
        'marked.py': `# Code generated by a tool.\nif True:\n  x = 1\n`,
        'caps.c': `/* DO NOT EDIT */\nint f(void) {\n  return 1;\n}\n`,
    });
    assert.deepEqual(got, ['plain.js', 'prose.js']);
});

test('the repository itself is at 4 spaces, with no file left out', () => {
    const run = spawnSync('python3', ['-I', SCRIPT, '--verify'], { cwd: ROOT, encoding: 'utf8', env: sandboxEnv() });
    assert.equal(run.status, 0, run.stdout);
    const src = fs.readFileSync(SCRIPT, 'utf8');
    assert.match(src, /^EXCLUDED_FILES = \{\}$/m, 'no file is excluded');
});
